"""Map camera: serves the rendered PNG + card-facing attributes."""
import logging

from homeassistant.components.camera import Camera
from homeassistant.config_entries import ConfigEntry
from homeassistant.core import HomeAssistant
from homeassistant.helpers.entity_platform import AddEntitiesCallback

from .const import DOMAIN

_LOGGER = logging.getLogger(__name__)


async def async_setup_entry(
    hass: HomeAssistant, entry: ConfigEntry, async_add_entities: AddEntitiesCallback
) -> None:
    coord = hass.data[DOMAIN][entry.entry_id]
    async_add_entities([CongaMapCamera(coord)])


class CongaMapCamera(Camera):
    _attr_name = "Conga map"

    def __init__(self, coord) -> None:
        super().__init__()
        self._coord = coord
        self._attr_unique_id = f"{DOMAIN}_map"

    @property
    def extra_state_attributes(self):
        attrs = dict(self._coord.latest or {})
        # lovelace-xiaomi-vacuum-map-card reads this attribute with
        # calibration_source: {camera: true} -> zero copy-paste
        if "calibration" in attrs:
            attrs["calibration_points"] = [
                {"vacuum": {"x": p["vacuum"]["X"], "y": p["vacuum"]["Y"]},
                 "map": {"x": int(p["map"]["X"]), "y": int(p["map"]["Y"])}}
                for p in attrs["calibration"]
            ]
        # card editor "Generate rooms config" contract: rooms dict keyed by
        # id with x0/y0/x1/y1 in map pixels + name -> predefined selections
        # are generated by the card itself, no manual config
        attrs["rooms"] = {
            str(r["ID"]): {
                "x0": r["BBoxPx"][0], "y0": r["BBoxPx"][1],
                "x1": r["BBoxPx"][2], "y1": r["BBoxPx"][3],
                "name": r.get("Name") or f"Room {r['ID']}",
            }
            for r in self._coord.rooms() if r.get("BBoxPx", [0, 0, 0, 0]) != [0, 0, 0, 0]
        }
        return attrs

    async def async_camera_image(self, width=None, height=None) -> bytes | None:
        return self._coord.png
